create or replace function public.bulk_insert_products(p_names text[])
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  raw_name text;
  clean_name text;
  affected integer;
  added integer := 0;
  skipped integer := 0;
begin
  if not public.is_admin() then raise exception 'FORBIDDEN' using errcode='42501'; end if;
  foreach raw_name in array coalesce(p_names,array[]::text[]) loop
    clean_name := btrim(regexp_replace(coalesce(raw_name,''), '\s+', ' ', 'g'));
    if clean_name = '' then continue; end if;
    insert into public.products(name,created_by) values(clean_name,auth.uid()) on conflict(name) do nothing;
    get diagnostics affected = row_count;
    if affected=1 then added:=added+1; else skipped:=skipped+1; end if;
  end loop;
  return jsonb_build_object('added',added,'skipped',skipped);
end;
$$;

create or replace function public.bulk_insert_locations(p_locations jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  item jsonb;
  b text;
  o text;
  affected integer;
  added integer := 0;
  skipped integer := 0;
begin
  if not public.is_admin() then raise exception 'FORBIDDEN' using errcode='42501'; end if;
  for item in select value from jsonb_array_elements(coalesce(p_locations,'[]'::jsonb)) loop
    b := btrim(regexp_replace(coalesce(item->>'branch',''), '\s+', ' ', 'g'));
    o := btrim(regexp_replace(coalesce(item->>'outlet',''), '\s+', ' ', 'g'));
    if b='' or o='' then continue; end if;
    insert into public.locations(branch,outlet,created_by) values(b,o,auth.uid()) on conflict(branch,outlet) do nothing;
    get diagnostics affected = row_count;
    if affected=1 then added:=added+1; else skipped:=skipped+1; end if;
  end loop;
  return jsonb_build_object('added',added,'skipped',skipped);
end;
$$;

create or replace function public.bulk_insert_mulia(p_records jsonb, p_last_import text default '')
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  item jsonb;
  row_data jsonb;
  rec_id text;
  sig text;
  affected integer;
  added integer := 0;
  skipped integer := 0;
begin
  if not public.is_admin() then raise exception 'FORBIDDEN' using errcode='42501'; end if;
  for item in select value from jsonb_array_elements(coalesce(p_records,'[]'::jsonb)) loop
    row_data := coalesce(item->'data','{}'::jsonb);
    if jsonb_typeof(row_data) <> 'object' or row_data='{}'::jsonb then continue; end if;
    rec_id := coalesce(nullif(item->>'id',''),'m' || replace(gen_random_uuid()::text,'-',''));
    sig := md5(row_data::text);
    insert into public.mulia_records(id,data,signature,created_by)
    values(rec_id,row_data,sig,auth.uid())
    on conflict do nothing;
    get diagnostics affected = row_count;
    if affected=1 then added:=added+1; else skipped:=skipped+1; end if;
  end loop;
  if btrim(coalesce(p_last_import,'')) <> '' then
    insert into public.settings(key,value) values('mulia_last_import',p_last_import)
    on conflict(key) do update set value=excluded.value;
  end if;
  return jsonb_build_object('added',added,'skipped',skipped);
end;
$$;

create or replace function public.delete_all_mulia()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted integer;
begin
  if not public.is_active_user() then raise exception 'FORBIDDEN' using errcode='42501'; end if;
  delete from public.mulia_records;
  get diagnostics deleted = row_count;
  insert into public.settings(key,value) values('mulia_last_import','')
  on conflict(key) do update set value='';
  return jsonb_build_object('deleted',deleted);
end;
$$;

create or replace function public.replace_risk_snapshot(p_records jsonb, p_meta jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  k text;
  c_kol1 integer := 0;
  c_lar integer := 0;
  c_npl integer := 0;
begin
  if not public.is_admin() then raise exception 'FORBIDDEN' using errcode='42501'; end if;
  delete from public.risk_records;
  foreach k in array array['kol1','lar','npl'] loop
    for item in select value from jsonb_array_elements(coalesce(p_records->k,'[]'::jsonb)) loop
      if jsonb_typeof(item)='object' then
        insert into public.risk_records(risk_type,data) values(k,item);
        if k='kol1' then c_kol1:=c_kol1+1;
        elsif k='lar' then c_lar:=c_lar+1;
        else c_npl:=c_npl+1;
        end if;
      end if;
    end loop;
  end loop;
  insert into public.risk_meta(id,file_name,last_import,sheet_name,source_rows,updated_by,updated_at)
  values(1,coalesce(p_meta->>'fileName',''),coalesce(p_meta->>'lastImport',''),coalesce(p_meta->>'sheetName',''),coalesce(nullif(p_meta->>'sourceRows','')::integer,0),auth.uid(),now())
  on conflict(id) do update set
    file_name=excluded.file_name,last_import=excluded.last_import,sheet_name=excluded.sheet_name,
    source_rows=excluded.source_rows,updated_by=excluded.updated_by,updated_at=excluded.updated_at;
  return jsonb_build_object('counts',jsonb_build_object('kol1',c_kol1,'lar',c_lar,'npl',c_npl));
end;
$$;

create or replace function public.clear_risk_snapshot()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted integer;
begin
  if not public.is_admin() then raise exception 'FORBIDDEN' using errcode='42501'; end if;
  delete from public.risk_records;
  get diagnostics deleted = row_count;
  insert into public.risk_meta(id,file_name,last_import,sheet_name,source_rows,updated_by,updated_at)
  values(1,'','','',0,auth.uid(),now())
  on conflict(id) do update set file_name='',last_import='',sheet_name='',source_rows=0,updated_by=auth.uid(),updated_at=now();
  return jsonb_build_object('deleted',deleted);
end;
$$;


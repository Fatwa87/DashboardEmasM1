create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  role text not null check (role in ('Admin','Umum','Disabled')),
  created_at timestamptz not null default now()
);

create table if not exists public.settings (
  key text primary key,
  value text not null
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name extensions.citext not null unique,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users(id) on delete set null
);

create table if not exists public.locations (
  id bigint generated by default as identity primary key,
  branch extensions.citext not null,
  outlet extensions.citext not null,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  constraint locations_branch_outlet_key unique(branch,outlet)
);

create table if not exists public.realizations (
  id text primary key,
  date date not null,
  branch text not null,
  outlet text not null,
  customer text not null,
  contract extensions.citext not null unique,
  product text not null,
  tenor integer not null check (tenor > 0),
  amount bigint not null check (amount > 0),
  created_at timestamptz not null default now(),
  created_by uuid not null default auth.uid() references auth.users(id) on delete restrict
);
create index if not exists idx_realizations_date on public.realizations(date);
create index if not exists idx_realizations_branch_outlet on public.realizations(branch,outlet);

create table if not exists public.mulia_records (
  id text primary key,
  data jsonb not null default '{}'::jsonb,
  signature text not null unique,
  created_at timestamptz not null default now(),
  created_by uuid not null default auth.uid() references auth.users(id) on delete restrict
);

create table if not exists public.risk_records (
  id bigint generated by default as identity primary key,
  risk_type text not null check (risk_type in ('kol1','lar','npl')),
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_risk_type on public.risk_records(risk_type);

create table if not exists public.risk_meta (
  id integer primary key check (id = 1),
  file_name text not null default '',
  last_import text not null default '',
  sheet_name text not null default '',
  source_rows integer not null default 0,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);


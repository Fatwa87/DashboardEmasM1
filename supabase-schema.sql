-- -----------------------------
-- PROFIL OTOMATIS DARI SUPABASE AUTH
-- Email internal hanya dipakai untuk login username Area / Outlet.
-- -----------------------------
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text;
  v_role text;
begin
  if lower(coalesce(new.email,'')) = 'area@closingemas.app' then
    v_username := 'Area';
    v_role := 'Admin';
  elsif lower(coalesce(new.email,'')) = 'outlet@closingemas.app' then
    v_username := 'Outlet';
    v_role := 'Umum';
  else
    v_username := coalesce(nullif(new.raw_user_meta_data->>'username',''), split_part(coalesce(new.email,'user'),'@',1) || '_' || left(new.id::text,8));
    v_role := 'Disabled';
  end if;

  insert into public.profiles(user_id,username,role)
  values(new.id,v_username,v_role)
  on conflict(user_id) do update set username=excluded.username, role=excluded.role;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_closing_emas on auth.users;
create trigger on_auth_user_created_closing_emas
after insert on auth.users
for each row execute function public.handle_new_auth_user();

